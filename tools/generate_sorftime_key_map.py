"""Generate sorftime_keys.py: simplified -> traditional key map for Sorftime responses.

Background: the fork-wide opencc (s2twp) conversion also rewrote the Chinese keys the scripts
use to read Sorftime responses, while the live API still answers with simplified keys.
The map is built from the upstream simplified sources and real response samples
(``--upstream <sha>``, needs the upstream objects locally) and from the current code
(traditional literals folded back with t2s). The committed output is checked by
tests/test_sorftime_keys.py.

Usage:  python tools/generate_sorftime_key_map.py --upstream 568be29
        python tools/generate_sorftime_key_map.py            # keep upstream part of the current map
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import subprocess
import sys
from pathlib import Path

import opencc

REPO_ROOT = Path(__file__).resolve().parent.parent
SKILLS = ("category-selection", "keyword-research", "product-research")
MODULE_NAME = "sorftime_keys.py"
CJK = re.compile(r"[一-鿿]")
KEY_IN_TEXT = re.compile(r'"([^"\\\n]{1,60})"\s*:')
# A key/label candidate: short, no sentence punctuation or spaces.
CANDIDATE = re.compile(r"^[\w一-鿿\-./%()（）]{1,40}$")

S2T = opencc.OpenCC("s2twp")
T2S = opencc.OpenCC("t2s")


def _candidates(text: str) -> set[str]:
    found = set()
    for piece in [text, *KEY_IN_TEXT.findall(text)]:
        if CJK.search(piece) and CANDIDATE.match(piece):
            found.add(piece)
    return found


def collect_code_keys(source: str) -> set[str]:
    """Chinese string literals in Python source that can be response keys."""
    found: set[str] = set()
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            found |= _candidates(node.value)
    return found


def collect_json_keys(value, out: set[str]) -> None:
    if isinstance(value, dict):
        for key, item in value.items():
            if isinstance(key, str) and CJK.search(key):
                out.add(key)
            collect_json_keys(item, out)
    elif isinstance(value, list):
        for item in value:
            collect_json_keys(item, out)


def skill_sources() -> list[Path]:
    paths = []
    for skill in SKILLS:
        paths += sorted((REPO_ROOT / "SKILLS" / "skills" / skill / "scripts").glob("*.py"))
    return [p for p in paths if p.name != MODULE_NAME]


def current_code_keys() -> set[str]:
    keys: set[str] = set()
    for path in skill_sources():
        keys |= collect_code_keys(path.read_text(encoding="utf-8"))
    return keys


def _git(*args: str) -> str:
    return subprocess.check_output(
        ["git", *args], cwd=REPO_ROOT, text=True, encoding="utf-8", errors="replace"
    )


def upstream_keys(sha: str) -> set[str]:
    """Simplified keys from upstream scripts and real response samples."""
    keys: set[str] = set()
    names = _git("ls-tree", "-r", "--name-only", sha).splitlines()
    for name in names:
        in_skill = any(f"SKILLS/skills/{s}/" in name for s in SKILLS)
        if in_skill and name.endswith(".py") and "/scripts/" in name:
            keys |= collect_code_keys(_git("show", f"{sha}:{name}"))
        elif name.startswith("REPORTS-ALL/") and name.endswith((".json", ".txt")):
            text = _git("show", f"{sha}:{name}")
            keys |= {k for k in KEY_IN_TEXT.findall(text) if CJK.search(k)}
            try:
                collect_json_keys(json.loads(text), keys)
            except ValueError:
                pass
    return {k for k in keys if CANDIDATE.match(k)}


def build_map(simplified: set[str], traditional: set[str]) -> dict[str, str]:
    mapping: dict[str, str] = {}
    for simp in simplified:
        trad = S2T.convert(simp)
        if trad != simp:
            mapping[simp] = trad
    for trad in traditional:
        simp = T2S.convert(trad)
        # Never overwrite an upstream-derived entry: t2s is lossy (e.g. 資料 -> 资料).
        if simp != trad and simp not in mapping and trad not in mapping.values():
            mapping[simp] = trad
    return dict(sorted(mapping.items()))


def load_current_map() -> dict[str, str]:
    path = REPO_ROOT / "SKILLS" / "skills" / SKILLS[0] / "scripts" / MODULE_NAME
    if not path.is_file():
        return {}
    namespace: dict = {}
    exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), namespace)  # noqa: S102
    return dict(namespace["KEY_MAP"])


TEMPLATE = '''"""Normalize Sorftime response keys (simplified) to the traditional keys the scripts use.

GENERATED by tools/generate_sorftime_key_map.py - do not edit by hand. The live Sorftime API
answers with simplified Chinese keys, while the scripts in this fork look keys up in
traditional Chinese. Input that already uses traditional keys passes through unchanged, so
both forms work. Only keys are converted; values and user-facing text are left alone.
"""

import re

KEY_MAP = {entries}

_QUOTED_KEY = re.compile(r'"([^"\\\\\\n]{{1,60}})"(\\s*:)')


def normalize_keys(value):
    """Return a copy of parsed JSON with simplified dict keys replaced by traditional ones."""
    if isinstance(value, dict):
        return {{
            KEY_MAP.get(key, key) if isinstance(key, str) else key: normalize_keys(item)
            for key, item in value.items()
        }}
    if isinstance(value, list):
        return [normalize_keys(item) for item in value]
    return value


def normalize_text(text):
    """Rewrite quoted simplified keys (``"key":``) in raw JSON text to traditional ones."""
    if not isinstance(text, str):
        return text

    def swap(match):
        return '"' + KEY_MAP.get(match.group(1), match.group(1)) + '"' + match.group(2)

    return _QUOTED_KEY.sub(swap, text)
'''


def render(mapping: dict[str, str]) -> str:
    lines = ["{"] + [f"    {k!r}: {v!r}," for k, v in mapping.items()] + ["}"]
    return TEMPLATE.format(entries="\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--upstream", help="upstream commit holding the simplified sources")
    args = parser.parse_args()

    simplified = upstream_keys(args.upstream) if args.upstream else set(load_current_map())
    mapping = build_map(simplified, current_code_keys())
    text = render(mapping)
    for skill in SKILLS:
        target = REPO_ROOT / "SKILLS" / "skills" / skill / "scripts" / MODULE_NAME
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {target.relative_to(REPO_ROOT)} ({len(mapping)} keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
