_QUOTED_KEY = re.compile(r'"([^"\\\n]{1,60})"(\s*:)')


def normalize_keys(value):
    """Return a copy of parsed JSON with simplified dict keys replaced by traditional ones."""
    if isinstance(value, dict):
        return {
            KEY_MAP.get(key, key) if isinstance(key, str) else key: normalize_keys(item)
            for key, item in value.items()
        }
    if isinstance(value, list):
        return [normalize_keys(item) for item in value]
    return value


def normalize_text(text):
    """Rewrite quoted simplified keys (``"key":``) in raw JSON text to traditional ones."""
    if not isinstance(text, str):
        return text

    def swap(match):
        return '"' + KEY_MAP.get(match.group(1), match.group(1)) + '"' + match.group(2)

    return _QUOTED_KEY.sub(swap, text)
